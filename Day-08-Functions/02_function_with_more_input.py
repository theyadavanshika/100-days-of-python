# Functions with more than 1 input

def greet_with(name, location):
    print(f"My name is {name}")
    print(f"I live in {location}")

# POSITIONAL ARGUMRNT
greet_with("Anshika", "Chicago")

def greet_with(name, location):
    print(f"My name is {name}")
    print(f"I live in {location}")

# KEYWORD ARGUMENT
greet_with(location = "Chicago", name = "Anshika")

